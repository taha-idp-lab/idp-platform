"""Generate the Grafana dashboard ConfigMap for FastAPI services (dashboard as code).

Usage: python3 deploy/monitoring/dashboards/generate.py && kubectl apply -f deploy/monitoring/dashboards/
Metrics come from prometheus-fastapi-instrumentator; the `service` label is added by the ServiceMonitor.
"""
import json
from pathlib import Path

DS = {"type": "prometheus", "uid": "${datasource}"}
SEL = 'service="$service", handler!="/metrics"'
RI = "[$__rate_interval]"


def target(expr, legend="", ref="A"):
    return {"datasource": DS, "expr": expr, "legendFormat": legend, "refId": ref}


def stat(id, title, expr, unit, x, decimals=None, thresholds=None):
    p = {"id": id, "type": "stat", "title": title, "datasource": DS,
         "gridPos": {"h": 4, "w": 6, "x": x, "y": 0},
         "targets": [target(expr)],
         "options": {"reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
                     "colorMode": "value", "graphMode": "area", "textMode": "value"},
         "fieldConfig": {"defaults": {"unit": unit, "color": {"mode": "thresholds"},
                                      "thresholds": {"mode": "absolute",
                                                     "steps": thresholds or [{"color": "green", "value": None}]}},
                         "overrides": []}}
    if decimals is not None:
        p["fieldConfig"]["defaults"]["decimals"] = decimals
    return p


def ts(id, title, targets, unit, x, y, w):
    return {"id": id, "type": "timeseries", "title": title, "datasource": DS,
            "gridPos": {"h": 8, "w": w, "x": x, "y": y}, "targets": targets,
            "fieldConfig": {"defaults": {"unit": unit, "custom": {"lineWidth": 2, "fillOpacity": 10}},
                            "overrides": []},
            "options": {"legend": {"displayMode": "list", "placement": "bottom"}, "tooltip": {"mode": "multi"}}}


def lat(q):
    return (f"histogram_quantile({q}, sum by (le) "
            f'(rate(http_request_duration_highr_seconds_bucket{{service="$service"}}{RI})))')


panels = [
    # Golden signals: availability, traffic, errors, latency
    stat(1, "Pods up", 'sum(up{service="$service"})', "none", 0,
         thresholds=[{"color": "red", "value": None}, {"color": "green", "value": 1}]),
    stat(2, "Requests / s", f"sum(rate(http_requests_total{{{SEL}}}{RI}))", "reqps", 6, decimals=2),
    stat(3, "Error rate (5xx)",
         f'100 * (sum(rate(http_requests_total{{{SEL}, status="5xx"}}{RI})) or vector(0))'
         f" / sum(rate(http_requests_total{{{SEL}}}{RI}))",
         "percent", 12, decimals=2,
         thresholds=[{"color": "green", "value": None}, {"color": "orange", "value": 1}, {"color": "red", "value": 5}]),
    stat(4, "Latency p95", lat(0.95), "s", 18, decimals=3,
         thresholds=[{"color": "green", "value": None}, {"color": "orange", "value": 0.3}, {"color": "red", "value": 1}]),
    ts(5, "Requests / s by endpoint",
       [target(f"sum by (handler) (rate(http_requests_total{{{SEL}}}{RI}))", "{{handler}}")], "reqps", 0, 4, 12),
    ts(6, "Responses by status class",
       [target(f"sum by (status) (rate(http_requests_total{{{SEL}}}{RI}))", "{{status}}")], "reqps", 12, 4, 12),
    ts(7, "Latency percentiles",
       [target(lat(0.5), "p50", "A"), target(lat(0.95), "p95", "B"), target(lat(0.99), "p99", "C")], "s", 0, 12, 24),
]

dashboard = {
    "uid": "fastapi-services", "title": "FastAPI services", "tags": ["idp", "fastapi"],
    "timezone": "browser", "schemaVersion": 39, "editable": True, "refresh": "30s",
    "time": {"from": "now-1h", "to": "now"},
    "description": "Golden signals for services created from the Backstage FastAPI template.",
    "templating": {"list": [
        {"name": "datasource", "label": "Data source", "type": "datasource", "query": "prometheus",
         "current": {}, "hide": 0},
        {"name": "service", "label": "Service", "type": "query", "datasource": DS,
         "query": {"query": "label_values(http_requests_total, service)", "refId": "service"},
         "definition": "label_values(http_requests_total, service)",
         "refresh": 2, "sort": 1, "current": {}, "hide": 0},
    ]},
    "panels": panels,
}

body = json.dumps(dashboard, indent=2)
header = """# GENERATED by generate.py - do not edit by hand.
# Grafana dashboard for every service created from the FastAPI template.
# Loaded automatically by the Grafana sidecar (label grafana_dashboard=1).
# Open with: http://localhost:3001/d/fastapi-services?var-service=<service-name>
apiVersion: v1
kind: ConfigMap
metadata:
  name: dashboard-fastapi-services
  namespace: monitoring
  labels:
    grafana_dashboard: "1"
data:
  fastapi-services.json: |
"""
out = Path(__file__).with_name("fastapi-services.yaml")
out.write_text(header + "\n".join("    " + line for line in body.splitlines()) + "\n")
print(f"wrote {out}")
